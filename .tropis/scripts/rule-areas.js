// Shared machinery: no part of this file is project-owned.
/**
 * A rule's area, and the text of every generated rule file.
 *
 * Three sources. A shipped rule's area is the project's data in
 * `.claude/rule-areas.json`; a project's own rule carries a `paths:` header at the top of
 * its `.claude/rules/*.md` file; a project's additions to a shipped rule are plain text in
 * `.claude/rule-additions/<name>.md`, joined after that rule's text. Claude Code reads the
 * header to load a rule when the agent first touches a matching file. generate-rules.mjs
 * writes the shipped rules' Claude Code files and every rule's Cursor file from these; the
 * rule-areas guard checks every rule has an area. See .claude/framework/DECISIONS.md,
 * "Rules load by area".
 *
 * Pure — text in, values out. No I/O.
 */
import { createHash } from 'node:crypto';

/**
 * A rule file's area and its body without the header.
 * @param {string} text The whole rule file.
 * @returns {{ paths: string[] | null, body: string }} `paths` is null when the file
 *   has no `paths:` header — such a rule loads in every Claude Code session.
 */
export function parseRule(text) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) return { paths: null, body: text };
  const line = /^paths:\s*(\[.*\])\s*$/m.exec(m[1]);
  return { paths: line ? JSON.parse(line[1]) : null, body: text.slice(m[0].length) };
}

/**
 * The problems with a project's areas file, as messages. Empty when it is sound.
 *
 * The areas file (`.claude/rule-areas.json`) holds the area of every shipped rule: an
 * object keyed by rule name, each value a non-empty array of glob strings. A glob may not
 * contain a comma — Cursor reads several globs from one comma-separated line, so a comma
 * inside one could not be written.
 *
 * @param {unknown} areas The parsed file.
 * @param {string[]} shipped Names of the shipped rules (file names without `.md`).
 * @returns {string[]}
 */
export function areaProblems(areas, shipped) {
  if (areas === null || typeof areas !== 'object' || Array.isArray(areas)) {
    return ['the areas file must be a JSON object keyed by shipped rule name'];
  }
  const problems = [];
  for (const name of shipped) {
    if (!(name in areas)) problems.push(`no area for the shipped rule "${name}"`);
  }
  for (const [name, globs] of Object.entries(areas)) {
    if (!shipped.includes(name)) {
      problems.push(`"${name}" is not a shipped rule (a project's own rule carries its own paths: header)`);
    } else if (!Array.isArray(globs) || globs.length === 0
      || globs.some((g) => typeof g !== 'string' || g === '')) {
      problems.push(`the area of "${name}" must be a non-empty array of glob strings`);
    } else if (globs.some((g) => g.includes(','))) {
      problems.push(`a glob of "${name}" contains a comma, which Cursor's globs line cannot carry`);
    }
  }
  return problems;
}

/** The line and sentence between a shipped rule and a project's additions to it. */
export const ADDITIONS_SEPARATOR = [
  "## This project's additions to the rule above",
  '',
  "The text above is the framework's rule. The text below is this project's own addition to it. Where the two contradict, follow the text below, and tell the operator which clause above you set aside and why.",
].join('\n');

/**
 * A shipped rule's text with the project's additions joined after it. Empty or absent
 * additions leave the text exactly as it was, so a rule with none is written as before.
 * @param {string} text The shipped text, no header. @param {string | null} additions
 */
export function joinAdditions(text, additions) {
  if (additions === null || additions.trim() === '') return text;
  return `${text.trimEnd()}\n\n${ADDITIONS_SEPARATOR}\n\n${additions.trim()}\n`;
}

/**
 * Why an additions file cannot be joined, or null. `.claude/rule-additions/<name>.md`
 * adds to the shipped rule of that name and carries no header of its own.
 * @param {string} name @param {string} text
 * @param {string[]} shipped Shipped rule names. @param {string[]} own The project's own rule names.
 */
export function additionsProblem(name, text, shipped, own) {
  if (!shipped.includes(name)) {
    return own.includes(name)
      ? `"${name}" is this project's own rule — add to .claude/rules/${name}.md itself`
      : `no shipped rule is named "${name}" (shipped: ${shipped.join(', ')}) — rename the file after one, or move its text into a rule of your own in .claude/rules/`;
  }
  if (/^\s*---[ \t]*\n/.test(text)) {
    return "an additions file carries no header — its area is the shipped rule's, set in .claude/rule-areas.json. Delete the header.";
  }
  return null;
}

const HASH_LINE = /^<!-- generated by \.tropis\/scripts\/generate-rules\.mjs · sha256:([0-9a-f]{64}) -->\n?$/;

const sha256 = (text) => createHash('sha256').update(text).digest('hex');

/** `text` (ending in a newline) followed by the line that fingerprints it. */
function stamped(text) {
  return `${text}<!-- generated by .tropis/scripts/generate-rules.mjs · sha256:${sha256(text)} -->\n`;
}

/**
 * A shipped rule's Claude Code file: header from the areas file, the text, the hash line.
 * @param {string[]} globs @param {string} text The shipped text, no header.
 */
export function renderClaude(globs, text) {
  return stamped(`---\npaths: ${JSON.stringify(globs)}\n---\n${text.trimEnd()}\n`);
}

/**
 * A rule's Cursor file, in the form measured to reach a Cursor agent (framework/rule-delivery.md):
 * `globs` unquoted and comma-separated, no other front-matter field.
 * @param {string} name @param {string[]} globs @param {string} body The text, no header.
 */
export function renderCursor(name, globs, body) {
  return stamped([
    '---',
    `description: ${name} rules (generated — do not edit)`,
    `globs: ${globs.join(', ')}`,
    'alwaysApply: false',
    '---',
    '',
    body.trimEnd(),
    '',
  ].join('\n'));
}

/**
 * Whether a file carries the generator's hash line, and if so whether it still matches
 * the content above it. `generated: false` means the file has no hash line at all.
 * @param {string} text
 * @returns {{ generated: boolean, intact: boolean }}
 */
export function checkStamp(text) {
  const lines = text.replace(/\n$/, '').split('\n');
  const last = lines.pop();
  const m = HASH_LINE.exec(`${last}\n`);
  if (!m) return { generated: false, intact: false };
  return { generated: true, intact: sha256(`${lines.join('\n')}\n`) === m[1] };
}
